#!/usr/bin/env julia
if abspath(PROGRAM_FILE) == @__FILE__
    using Pkg
    Pkg.activate(dirname(@__DIR__))
    Pkg.instantiate()
end

using BenchmarkTools
using ArgParse
using DataStructures
using JSON
using SparseArrays
using LinearAlgebra
using Finch
using TensorMarket

s = ArgParseSettings("Run outer product experiments.")
@add_arg_table! s begin
    "--ncpu"
    help = "number of CPUs"
    arg_type = Int
    default = 16
    "--output", "-o"
    arg_type = String
    help = "output file path"
    default = "outer_results.json"
    "--method", "-m"
    arg_type = String
    action = :append_arg
    help = "method keyword (repeat -m to run several; default: all)"
end
parsed_args = parse_args(ARGS, s)

include("outer_mkl.jl")
include("wingspan_outer.jl")
include("birdseed_outer.jl")

# Generated by make_outer_data.jl. C = A * B'.
A = SparseMatrixCSC(fread(joinpath(@__DIR__, "data", "outer_A.ttx")))
B = SparseMatrixCSC(fread(joinpath(@__DIR__, "data", "outer_B.ttx")))

methods = OrderedDict(
    "mkl" => outer_mkl,
    "wingspan_outer" => wingspan_outer,
    "birdseed_outer" => birdseed_outer,
)

selected = something(parsed_args["method"], String[])
if !isempty(selected)
    for name in selected
        @assert haskey(methods, name) "Unrecognized method $name"
    end
    methods = OrderedDict(name => methods[name] for name in selected)
end

ncpu = parsed_args["ncpu"]
results = []
C_ref = nothing
for (key, method) in methods
    @info "testing" key
    res = method(A, B, ncpu)
    C = SparseMatrixCSC(res.C)
    global C_ref = something(C_ref, C)
    norm(C_ref - C) / norm(C_ref) < 0.01 || @warn("incorrect result via norm for $key")
    @info "results" key res.time
    push!(results, OrderedDict(
        "time" => res.time,
        "n_threads" => Threads.nthreads(),
        "method" => key,
        "dataset" => "outer",
    ))
    write(parsed_args["output"], JSON.json(results, 4))
end
